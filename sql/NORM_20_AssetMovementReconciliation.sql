UPDATE target
SET target.Amount=source.Amount,target.SourceReference=@Source,target.IsDeactivated=0
FROM dbo.tblNORM_SourceAssetMovementFigure target
INNER JOIN @Figures source
    ON source.RowCode=target.RowCode AND source.AssetClassCode=target.AssetClassCode
WHERE target.SourceFileHash=@Hash;

INSERT dbo.tblNORM_SourceAssetMovementFigure
    (SourceFileHash,RowCode,AssetClassCode,Amount,SourceReference)
SELECT @Hash,source.RowCode,source.AssetClassCode,source.Amount,@Source
FROM @Figures source
WHERE NOT EXISTS
(
    SELECT 1 FROM dbo.tblNORM_SourceAssetMovementFigure target
    WHERE target.SourceFileHash=@Hash AND target.RowCode=source.RowCode
      AND target.AssetClassCode=source.AssetClassCode
);

