    (
        SourceAssetMovementFigureId BIGINT IDENTITY(1,1) NOT NULL
            CONSTRAINT PK_tblNORM_SourceAssetMovementFigure PRIMARY KEY,
        SourceFileHash CHAR(64) NOT NULL,
        RowCode VARCHAR(40) NOT NULL,
        AssetClassCode VARCHAR(60) NOT NULL,
        Amount DECIMAL(19,3) NOT NULL,
        SourceReference NVARCHAR(300) NULL,
        IsDeactivated BIT NOT NULL
            CONSTRAINT DF_tblNORM_SourceAssetMovementFigure_IsDeactivated DEFAULT (0),
        CreatedUtc DATETIME2(3) NOT NULL
